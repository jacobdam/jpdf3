//! `build`: regress manifest from pinned git sources (specs/tooling/corpus.md, items 3 and 5).

use std::collections::HashSet;
use std::path::{Path, PathBuf};

use jpdf_arlington::fetch::git_out;

use crate::Error;
use crate::manifest::{Entry, Manifest};
use crate::sources::{MAX_BUILD_FILE, Source};

/// The ref that keeps a source's pinned commit alive in its cache repository.
pub const PIN_REF: &str = "refs/jpdf/pinned";

/// One `*.pdf` candidate from a tree listing.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TreeFile {
    pub path: String,
    pub blob: String,
    pub size: u64,
}

/// Parses `git ls-tree -r -l -z` output and keeps regular-file `*.pdf` blobs (any case) of
/// 1 byte to [`MAX_BUILD_FILE`]. Malformed entries are errors.
pub fn select_pdfs(listing: &[u8]) -> Result<Vec<TreeFile>, String> {
    let mut out = Vec::new();
    for raw in listing.split(|b| *b == 0).filter(|e| !e.is_empty()) {
        let entry =
            std::str::from_utf8(raw).map_err(|_| "ls-tree entry is not UTF-8".to_string())?;
        let bad = || format!("bad ls-tree entry {entry:?}");
        let (meta, path) = entry.split_once('\t').ok_or_else(bad)?;
        // "<mode> SP <type> SP <id> SP+ <size>" (size is right-aligned, "-" for non-blobs).
        let fields: Vec<&str> = meta.split(' ').filter(|f| !f.is_empty()).collect();
        let [mode, kind, id, size] = fields[..] else {
            return Err(bad());
        };
        if !path.to_ascii_lowercase().ends_with(".pdf") {
            continue;
        }
        if kind != "blob" || !(mode == "100644" || mode == "100755") {
            continue; // symlinks (120000), submodules (commit), trees
        }
        if id.len() != 40
            || !id
                .bytes()
                .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
        {
            return Err(bad());
        }
        let size: u64 = size.parse().map_err(|_| bad())?;
        if size == 0 || size > MAX_BUILD_FILE {
            continue;
        }
        if path.chars().any(char::is_control) {
            continue; // can't be a manifest URL
        }
        out.push(TreeFile {
            path: path.to_string(),
            blob: id.to_string(),
            size,
        });
    }
    out.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(out)
}

/// Merges per-source selections in priority order, keeping the first occurrence of each blob,
/// and returns the manifest (rows sorted by blob id).
pub fn merge(tier: &str, sources: &[(Source, Vec<TreeFile>)]) -> Result<Manifest, Error> {
    let mut seen = HashSet::new();
    let mut entries = Vec::new();
    let mut comments = vec![
        format!("Agent {tier} corpus. Generated by `jpdf-corpus build {tier}`; do not edit."),
        "Spec: specs/tooling/corpus.md. Files are fetched, never committed (CONSTITUTION 18)."
            .to_string(),
    ];
    for (src, files) in sources {
        let mut taken = 0usize;
        for f in files {
            if !seen.insert(f.blob.clone()) {
                continue;
            }
            let url = src.url(&f.path);
            crate::manifest::check_url(&url)
                .map_err(|m| Error::Build(format!("{}: {}: {m}", src.name, f.path)))?;
            entries.push(Entry {
                blob: f.blob.clone(),
                size: f.size,
                url,
            });
            taken = taken.saturating_add(1);
        }
        comments.push(format!(
            "source {} {} {} files={taken} license: {}",
            src.name, src.repo, src.commit, src.license
        ));
    }
    comments.push("columns: git_blob_sha1<TAB>size<TAB>url".to_string());
    entries.sort_by(|a, b| a.blob.cmp(&b.blob));
    Ok(Manifest { comments, entries })
}

/// The cache repository of one source.
pub fn repo_path(cache: &Path, src: &Source) -> PathBuf {
    cache.join("git").join(format!("{}.git", src.name))
}

/// Fetches (once) and verifies a source's pinned commit, then lists its PDFs.
pub fn list_source(cache: &Path, src: &Source) -> Result<Vec<TreeFile>, Error> {
    let e = |m: String| Error::Build(format!("{}: {m}", src.name));
    let git = |dir: &Path, args: &[&str]| git_out(dir, args, None).map_err(|x| e(x.to_string()));
    let repo = repo_path(cache, src);
    if !repo.exists() {
        std::fs::create_dir_all(&repo).map_err(|source| Error::Io {
            path: repo.display().to_string(),
            source,
        })?;
        git(&repo, &["init", "--bare", "--quiet"])?;
    }
    let bare = git(&repo, &["rev-parse", "--is-bare-repository"]).map_err(|x| {
        e(format!(
            "{} is not a usable cache ({x}); delete it",
            repo.display()
        ))
    })?;
    if String::from_utf8_lossy(&bare).trim() != "true" {
        return Err(e(format!(
            "{} is not a bare repository; delete it",
            repo.display()
        )));
    }
    let commit_ref = format!("{}^{{commit}}", src.commit);
    if git(&repo, &["cat-file", "-e", &commit_ref]).is_err() {
        git(
            &repo,
            &[
                "fetch",
                "--quiet",
                "--depth",
                "1",
                "--no-tags",
                src.repo,
                src.commit,
            ],
        )?;
    }
    git(&repo, &["update-ref", PIN_REF, src.commit])?;
    git(
        &repo,
        &[
            "fsck",
            "--full",
            "--strict",
            "--no-dangling",
            "--no-progress",
        ],
    )?;
    let got = git(&repo, &["rev-parse", "--verify", &commit_ref])?;
    let got = String::from_utf8_lossy(&got).trim().to_string();
    if got != src.commit {
        return Err(e(format!("commit is {got}, pinned {}", src.commit)));
    }
    let listing = git(&repo, &["ls-tree", "-r", "-l", "-z", src.commit])?;
    select_pdfs(&listing).map_err(e)
}

#[cfg(test)]
mod tests {
    use super::*;

    const A: &str = "76e8430a4975ba221883c16a075a4e9fd28c66d0";
    const B: &str = "9bd93307be15a053ae21638e1c9f5ec63cff8a23";
    const C: &str = "0821ccdbd7616c4fcbcf6e476ab8a1595c2b15cb";

    fn listing(rows: &[&str]) -> Vec<u8> {
        rows.iter()
            .flat_map(|r| [r.as_bytes(), b"\0"].concat())
            .collect()
    }

    #[test]
    fn selection_rules() {
        let l = listing(&[
            &format!("100644 blob {A}     100\ttest/b.pdf"),
            &format!("100755 blob {B}       7\ttest/A.PDF"),
            &format!("100644 blob {C}     100\ttest/x.pdf.link"),
            &format!("120000 blob {C}      10\ttest/link.pdf"),
            &format!("160000 commit {C}       -\tsub.pdf"),
            &format!("100644 blob {C}       0\tempty.pdf"),
            &format!("100644 blob {C} 16777217\thuge.pdf"),
            &format!("100644 blob {C} 16777216\tmax.pdf"),
            &format!("100644 blob {C}       1\tnew\nline.pdf"),
            &format!("100644 blob {C}       9\tnotes.txt"),
        ]);
        let got = select_pdfs(&l).unwrap();
        let names: Vec<_> = got.iter().map(|f| (f.path.as_str(), f.size)).collect();
        assert_eq!(
            names,
            [
                ("max.pdf", 16_777_216),
                ("test/A.PDF", 7),
                ("test/b.pdf", 100)
            ]
        );
        assert_eq!(got[1].blob, B);
    }

    #[test]
    fn malformed_entries_are_errors() {
        for bad in [
            "100644 blob abc 5\tx.pdf".to_string(),
            format!("100644 blob {A}\tx.pdf"),
            format!("100644 blob {A} -5\tx.pdf"),
            format!("100644 blob {A} 5 x.pdf"),
            format!("100644 blob {} 5\tx.pdf", A.to_uppercase()),
        ] {
            assert!(select_pdfs(&listing(&[&bad])).is_err(), "{bad:?}");
        }
        assert!(select_pdfs(b"\xff\0").is_err());
    }

    #[test]
    fn merge_dedupes_in_priority_order_and_sorts() {
        let s = crate::sources::REGRESS;
        let f = |path: &str, blob: &str| TreeFile {
            path: path.into(),
            blob: blob.into(),
            size: 3,
        };
        let m = merge(
            "regress",
            &[
                (s[0], vec![f("a.pdf", B), f("b.pdf", B)]),
                (s[4], vec![f("c d.pdf", A), f("e.pdf", B)]),
            ],
        )
        .unwrap();
        let urls: Vec<_> = m.entries.iter().map(|e| e.url.as_str()).collect();
        assert_eq!(
            urls,
            [
                format!(
                    "https://gitlab.freedesktop.org/poppler/test/-/raw/{}/c d.pdf",
                    s[4].commit
                ),
                format!(
                    "https://raw.githubusercontent.com/mozilla/pdf.js/{}/a.pdf",
                    s[0].commit
                ),
            ]
        );
        assert!(
            m.comments
                .iter()
                .any(|c| c.starts_with("source pdfjs ") && c.contains("files=1 "))
        );
        assert!(
            m.comments
                .iter()
                .any(|c| c.starts_with("source poppler ") && c.contains("files=1 "))
        );
        let text = crate::manifest::write(&m);
        assert_eq!(crate::manifest::parse("m", text.as_bytes()).unwrap(), m);
    }
}
