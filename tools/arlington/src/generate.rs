//! Rust tables from the model (specs/tooling/arlington.md, "Generated tables").
//!
//! The output is one self-contained Rust file: type definitions, then `OBJECTS`, sorted by
//! name so `binary_search_by` works. Output is deterministic: the same model gives the same
//! bytes.

use std::fmt::Write as _;

use crate::model::{Gate, Gated, Indirect, KeyName, Model, Required, Since, Version};

const PRELUDE: &str = r#"
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct Version {
    pub major: u8,
    pub minor: u8,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum ValueType {
    Array, Bitmask, Boolean, Date, Dictionary, Integer, Matrix, Name, NameTree, Null,
    Number, NumberTree, Rectangle, Stream, String, StringAscii, StringByte, StringText,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Gate {
    SinceVersion(Version),
    BeforeVersion(Version),
    IsPdfVersion(Version),
    Deprecated(Version),
    Extension(&'static str),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum KeyName {
    Name(&'static str),
    Index(u32),
    IndexRepeat(u32),
    Wildcard,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Since {
    Version(Version),
    Extension { name: &'static str, version: Option<Version> },
    Expr(&'static str),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Required {
    Always,
    Never,
    If(&'static str),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Indirect {
    Must,
    May,
    MustBeDirect,
    Expr(&'static str),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Link {
    pub gates: &'static [Gate],
    pub object: &'static str,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TypeAlt {
    pub gates: &'static [Gate],
    pub ty: ValueType,
    pub links: &'static [Link],
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Key {
    pub key: KeyName,
    pub types: &'static [TypeAlt],
    pub since: Since,
    pub deprecated: Option<Version>,
    pub required: Required,
    /// One entry for all types, or one per type.
    pub indirect: &'static [Indirect],
    pub inheritable: bool,
    pub default_value: &'static str,
    pub possible_values: &'static str,
    pub special_case: &'static str,
    pub note: &'static str,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Object {
    pub name: &'static str,
    pub keys: &'static [Key],
}
"#;

/// Renders the tables. `source` describes where the model came from (commit or directory)
/// and goes into the header comment.
pub fn render(model: &Model, source: &str) -> String {
    let mut out = String::new();
    // `writeln!` into a `String` cannot fail; the results are ignored on purpose.
    let _ = writeln!(
        out,
        "// @generated by jpdf-arlington (tools/arlington) from the Arlington PDF Model,\n\
         // {}. Do not edit; regenerate with `cargo xtask arlington`.\n\
         // Arlington PDF Model: Copyright PDF Association, Inc.; Apache License 2.0.",
        one_line(source)
    );
    out.push_str(PRELUDE);
    let _ = writeln!(
        out,
        "\npub const OBJECT_COUNT: usize = {};\npub const KEY_COUNT: usize = {};",
        model.objects.len(),
        model.key_count()
    );
    out.push_str(
        "\n/// Every object definition, sorted by name.\npub static OBJECTS: &[Object] = &[\n",
    );
    for (name, object) in &model.objects {
        let _ = writeln!(out, "    Object {{ name: {name:?}, keys: &[");
        for k in &object.keys {
            let _ = writeln!(out, "        Key {{");
            let _ = writeln!(out, "            key: {},", key_name(&k.key));
            out.push_str("            types: &[");
            for alt in &k.types {
                let _ = write!(
                    out,
                    "TypeAlt {{ gates: {}, ty: ValueType::{}, links: &[",
                    gates(&alt.ty),
                    alt.ty.value.variant()
                );
                for l in &alt.links {
                    let _ = write!(
                        out,
                        "Link {{ gates: {}, object: {:?} }}, ",
                        gates(l),
                        l.value
                    );
                }
                out.push_str("] }, ");
            }
            out.push_str("],\n");
            let _ = writeln!(out, "            since: {},", since(&k.since));
            let _ = writeln!(
                out,
                "            deprecated: {},",
                k.deprecated
                    .map_or_else(|| "None".to_string(), |v| format!("Some({})", version(v)))
            );
            let _ = writeln!(out, "            required: {},", required(&k.required));
            out.push_str("            indirect: &[");
            for i in &k.indirect {
                let _ = write!(out, "{}, ", indirect(i));
            }
            out.push_str("],\n");
            let _ = writeln!(out, "            inheritable: {},", k.inheritable);
            let _ = writeln!(out, "            default_value: {:?},", k.default_value);
            let _ = writeln!(out, "            possible_values: {:?},", k.possible_values);
            let _ = writeln!(out, "            special_case: {:?},", k.special_case);
            let _ = writeln!(out, "            note: {:?},", k.note);
            out.push_str("        },\n");
        }
        out.push_str("    ] },\n");
    }
    out.push_str("];\n");
    out
}

fn one_line(s: &str) -> String {
    s.chars()
        .map(|c| if c.is_control() { ' ' } else { c })
        .collect()
}

fn version(v: Version) -> String {
    format!("Version {{ major: {}, minor: {} }}", v.major, v.minor)
}

fn gates<T>(g: &Gated<T>) -> String {
    let items: Vec<String> = g
        .gates
        .iter()
        .map(|gate| match gate {
            Gate::SinceVersion(v) => format!("Gate::SinceVersion({})", version(*v)),
            Gate::BeforeVersion(v) => format!("Gate::BeforeVersion({})", version(*v)),
            Gate::IsPdfVersion(v) => format!("Gate::IsPdfVersion({})", version(*v)),
            Gate::Deprecated(v) => format!("Gate::Deprecated({})", version(*v)),
            Gate::Extension(n) => format!("Gate::Extension({n:?})"),
        })
        .collect();
    format!("&[{}]", items.join(", "))
}

fn key_name(k: &KeyName) -> String {
    match k {
        KeyName::Name(n) => format!("KeyName::Name({n:?})"),
        KeyName::Index(i) => format!("KeyName::Index({i})"),
        KeyName::IndexRepeat(i) => format!("KeyName::IndexRepeat({i})"),
        KeyName::Wildcard => "KeyName::Wildcard".into(),
    }
}

fn since(s: &Since) -> String {
    match s {
        Since::Version(v) => format!("Since::Version({})", version(*v)),
        Since::Extension { name, version: v } => format!(
            "Since::Extension {{ name: {name:?}, version: {} }}",
            v.map_or_else(|| "None".to_string(), |v| format!("Some({})", version(v)))
        ),
        Since::Expr(e) => format!("Since::Expr({e:?})"),
    }
}

fn required(r: &Required) -> String {
    match r {
        Required::Always => "Required::Always".into(),
        Required::Never => "Required::Never".into(),
        Required::If(c) => format!("Required::If({c:?})"),
    }
}

fn indirect(i: &Indirect) -> String {
    match i {
        Indirect::Must => "Indirect::Must".into(),
        Indirect::May => "Indirect::May".into(),
        Indirect::MustBeDirect => "Indirect::MustBeDirect".into(),
        Indirect::Expr(e) => format!("Indirect::Expr({e:?})"),
    }
}
